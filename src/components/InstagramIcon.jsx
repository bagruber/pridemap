// Lucide has no Instagram glyph (it dropped the brand marks), and pulling in
// react-icons for this one icon cost a whole dependency. Drawn to match
// Lucide's conventions: 24-unit box, round joins, currentColor.
export default function InstagramIcon({ size = 13, ...props }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      <rect x="2" y="2" width="20" height="20" rx="5" />
      <circle cx="12" cy="12" r="4" />
      <circle cx="17.5" cy="6.5" r="1.2" fill="currentColor" stroke="none" />
    </svg>
  )
}
